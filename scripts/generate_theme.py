"""Generate the GPUI adapter and Rust palette from the approved design tokens."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
j = json.loads((ROOT / 'assets/theme/tokens.json').read_text(encoding='utf-8'))
colors = j['color']['tokens']
lines = ['// Generated by scripts/generate_theme.py; edit assets/theme/tokens.json.', 'use gpui::{Hsla, rgb, rgba};', '#[derive(Clone, Copy, Debug)]', 'pub struct Palette {']
for t in colors:
    lines.append('    pub ' + t['name'].replace('-', '_') + ': Hsla,')
lines += ['}']
for mode in ('dark', 'light'):
    lines += [f'pub fn {mode}() -> Palette {{', '    Palette {']
    for t in colors:
        v = t['value'][mode][1:]
        lines.append(f"        {t['name'].replace('-', '_')}: {'rgba' if len(v)==8 else 'rgb'}(0x{v}).into(),")
    lines += ['    }', '}']
lines += ['pub mod dark {']
for t in colors:
    lines.append(f"    pub const {t['name'].replace('-', '_').upper()}: u32 = 0x{t['value']['dark'][1:]};")
lines += ['}']
(ROOT/'crates/frontend/src/theme_palette.rs').write_text('\n'.join(lines)+'\n')
c = {t['name']:t['value']['dark'] for t in colors}
mapping = {
 'background':'bg','foreground':'ink','border':'border','accent.background':'accent-soft','accent.foreground':'accent-text',
 'muted.background':'panel-raised','muted.foreground':'ink-muted','input.background':'panel-sunken','input.border':'border-strong',
 'primary.background':'accent-soft','primary.foreground':'accent-text','primary.hover.background':'accent-soft','primary.active.background':'panel-sunken',
 'secondary.background':'panel-raised','secondary.foreground':'ink-muted',
 'sidebar.background':'panel-sunken','sidebar.foreground':'ink','sidebar.accent.background':'accent-soft','sidebar.accent.foreground':'accent-text',
 'popover.background':'panel','popover.foreground':'ink','list.background':'panel','list.head.background':'panel-raised',
 'list.active.background':'accent-soft','list.active.border':'accent-text','list.hover.background':'panel-raised',
 'tab_bar.background':'bg','tab.background':'bg','tab.foreground':'ink-muted','tab.active.background':'bg','tab.active.foreground':'ink',
 'table.background':'panel','table.head.background':'panel-raised','table.row.hover.background':'panel-raised',
 'progress.bar.background':'accent-text','ring':'focus','caret':'accent-text',
 'danger.background':'danger','danger.foreground':'danger','success.background':'success','success.foreground':'success',
 'warning.background':'warning','warning.foreground':'warning','info.background':'accent-text','info.foreground':'accent-text',
}
cc={k:c[v] for k,v in mapping.items()}
cc.update({'button.background':'#ffffff00','button.foreground':c['ink-muted'],'button.hover.background':'#ffffff0a','button.active.background':'#ffffff05'})
for variant in ('primary','info','success','warning'):
    cc.update({f'button.{variant}.background':'linear-gradient(90deg, #123543, #0d2029)', f'button.{variant}.hover.background':'linear-gradient(90deg, #174252, #0f2731)', f'button.{variant}.active.background':'#0d2029',f'button.{variant}.foreground':c['accent-text']})
cc.update({'button.danger.background':'linear-gradient(90deg, #4a1919, #2e1010)','button.danger.hover.background':'linear-gradient(90deg, #5a1e1e, #361313)','button.danger.active.background':'#2e1010','button.danger.foreground':c['danger']})
config={'name':'Wachiland','themes':[{'name':'Wachiland Dark','mode':'dark','font.family':'Noto Sans','font.size':14,'radius':0,'radius.lg':0,'shadow':False,'colors':cc}]}
(ROOT/'assets/theme/wachiland.json').write_text(json.dumps(config,indent=2)+'\n')
print('Generated Wachiland palette and GPUI theme')
